public class ExplicitCastingeg {
    public static void main(String[] args) {

        double myDouble=9.15;
        int myInt=(int) myDouble;


        //this is explicitcasting as the value is getting stores more double but we converting it into the int so only the 9 is getting stored
        System.out.println(myInt);

    }

}
